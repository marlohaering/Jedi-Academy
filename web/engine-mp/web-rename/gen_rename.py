#!/usr/bin/env python3
"""Generate per-module rename headers so cgame, ui and the renderer can be linked
statically into one WebAssembly binary.

Each of these modules normally lives in its own shared library and carries its own
copies of shared code (q_shared, q_math, bg_*, ui_shared ...). Linked together those
copies collide. We list the strong global symbols each module defines (llvm-nm on the
first-pass static libraries), and for every symbol that is also defined by another
module or by the engine we emit `#define sym <prefix>_sym` into that module's header.
The header is force-included (-include) into every translation unit of the module, so
the module keeps calling its own copy under the new name.

The entry points (GetModuleAPI / GetRefAPI) are always renamed so the engine can
reference each one explicitly.

usage: gen_rename.py <llvm-nm> <out dir> engine=<objs...> cgame=<lib.a> ui=<lib.a> renderer=<lib.a>
"""
import re
import subprocess
import sys

PREFIX = {'cgame': 'cgame', 'ui': 'ui', 'renderer': 'renderer'}
ENTRY = {'cgame': 'GetModuleAPI', 'ui': 'GetModuleAPI', 'renderer': 'GetRefAPI'}
STRONG = set('TDBRC')  # text, data, bss, rodata, common
IDENT = re.compile(r'^[A-Za-z_][A-Za-z0-9_]*$')


def defined(nm, files):
    out = subprocess.run([nm, '--defined-only', '-C', *files], capture_output=True, text=True).stdout
    syms = set()
    for line in out.splitlines():
        parts = line.split(None, 2)
        if len(parts) < 3 or parts[1] not in STRONG:
            continue
        name = parts[2]
        # C++: "Foo::bar(int)" -> outermost identifier "Foo"; "bar(int)" -> "bar"
        name = name.split('(')[0].split('<')[0]
        name = name.split('::')[0].strip()
        if name.startswith('operator') or name.startswith('std') or not IDENT.match(name):
            continue
        syms.add(name)
    return syms


def main():
    nm, outdir = sys.argv[1], sys.argv[2]
    groups = {}
    for arg in sys.argv[3:]:
        key, _, path = arg.partition('=')
        groups.setdefault(key, []).append(path)
    syms = {k: defined(nm, v) for k, v in groups.items()}
    for mod in ('cgame', 'ui', 'renderer'):
        others = set().union(*(s for k, s in syms.items() if k != mod))
        clash = sorted((syms[mod] & others) | {ENTRY[mod]})
        with open(f'{outdir}/{mod}.h', 'w') as fh:
            fh.write(f'// generated by gen_rename.py - {len(clash)} symbols\n#pragma once\n')
            for s in clash:
                fh.write(f'#define {s} {PREFIX[mod]}_{s}\n')
        print(f'{mod}: {len(clash)} renamed symbols')


if __name__ == '__main__':
    main()
